"""M21.4.11-R3.3: exhaustive legacy reconnect recovery partition.

Startup recovery and the read-only ``recovery legacy-reconnect-preflight``
command share this single decision engine.  The engine performs an
EXHAUSTIVE three-way partition over every historical SEALING reconnect
intent:

A. ``PROVEN_LEGITIMATE`` — durable identity proves the intent is a genuine
   REQ-103 intent-only crash: startup materializes exactly one STARTED.
B. ``PROVEN_EXTENSION`` — durable identity proves the intent is a
   pre-R3 pending-gap extension orphan: startup ignores lifecycle
   materialization.
C. ``AMBIGUOUS`` — durable identity cannot prove either direction: startup
   fails closed unless an exact, strongly-bound operator classification
   authority resolves it.

There is no fourth outcome: uncertainty means AMBIGUOUS, never a default
materialization and never a default ignore.

UTC wall-clock timestamps are retained for operator diagnostics only.  UTC
ordering NEVER determines whether a candidate is ambiguous, whether an
interval participates in the classification universe, or whether an intent
is materialized or suppressed.  CLOSED lifecycle pairs remain exact
authority even when their wall timestamps are inverted (``NON_MONOTONIC``).

Intent provenance (M21.4.11-R3.3, REV-001):

The R3.2 "no possible parent -> proven_legitimate" proof is REMOVED: the
searched historical universe is not mathematically complete (malformed
lifecycle authority can disappear from it), so absence of a parent is
never positive legitimacy evidence.  Intents generated by the R3.3+
runtime instead carry the durable ``intent_schema``
``reconnect-seal-intent.v2``; under the versioned runtime prevention
contract a pure extension can never mint an independent orphan gap
identity (it reuses the pending gap's canonical identity) and
decision-point-2 uses a fresh genuine logical gap, so a versioned ABSENT
fresh intent safely represents the REQ-103 crash shape.  Unversioned
(pre-R3) legacy candidates may only use independently-sound positive
proofs (trustworthy ``verified_frames > 0`` or the exact
completing-connection proof); everything else is AMBIGUOUS.

Malformed historical lifecycle authority is NEVER silently dropped.
Unkeyable STARTED/COMPLETED rows and identity-degraded CLOSED pairs are
surfaced as explicit degraded-authority predecision blockers: their
existence blocks eligibility and widens uncertainty instead of shrinking
the possible-parent universe.

Authority ordering (M21.4.11-R3.2):

1. exact same-gap lifecycle CLOSED/OPEN handling;
2. durable automatic proofs;
3. competing-gap invariants (REQ-104);
4. determine AMBIGUOUS;
5. only then consult the operator authority.

An authority entry resolves ONLY an AMBIGUOUS candidate.  An entry bound
to a candidate whose durable facts already prove a decision is a
CONTRADICTION and fails closed.  Entries must bind to the exact immutable
persisted record (``chunk_id`` + canonical seal-intent digest +
``verified_frames``); stale, duplicate, or unmatched entries fail closed.
Startup always recomputes the automatic decision first, so a later
context change that produces a PROVEN decision or HARD_CONFLICT is never
overridden by an older authority.
"""

