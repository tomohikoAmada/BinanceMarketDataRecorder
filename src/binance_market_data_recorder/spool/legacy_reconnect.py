#: Production Ubuntu system-service authority installation contract
#: (M21.4.11-R3.4 REV-003-R3.3-001).  The authority file lives in the
#: ROOT-CONTROLLED configuration namespace (alongside the loaded Recorder
#: configuration file), never inside the service-writable data root: the
#: service principal owns the data root directory and could otherwise
#: unlink/rename/replace the authority pathname even though file mode
#: 0640 denies content writes.  The parent directory contract is:
#: owner=root group=orangepi mode=0750 (root/operator replace; service
#: group traverse+read; no write).  The file contract is:
#: owner=root group=orangepi mode=0640 (root/operator write; service
#: group read; everyone else nothing).  The recorder never writes or
#: edits the file; deployment installs it atomically with these exact
#: owner/group/mode before rename.  The deterministic
#: permission-contract test asserts these constants (file AND parent)
#: against the systemd service identity (User=orangepi Group=orangepi).
CLASSIFICATION_AUTHORITY_OWNER = "root"
CLASSIFICATION_AUTHORITY_GROUP = "orangepi"
CLASSIFICATION_AUTHORITY_MODE = 0o640
CLASSIFICATION_AUTHORITY_PARENT_OWNER = "root"
CLASSIFICATION_AUTHORITY_PARENT_GROUP = "orangepi"
CLASSIFICATION_AUTHORITY_PARENT_MODE = 0o750


def classification_authority_path(
    *, config_file: Path | None, data_root: Path
) -> Path:
    """Resolve the classification authority location.

    The authority lives alongside the loaded Recorder configuration
    (``config_file.parent``), not alongside mutable service data: the
    production config namespace ``/etc/binance-market-data-recorder`` is
    root-controlled and not writable by the service principal, so the
    service can read the authority but can never unlink/rename/replace
    its pathname (M21.4.11-R3.4).  Interactive configs follow the same
    rule next to their config file with their local ownership semantics.
    Only when NO configuration file is loaded (interactive defaults,
    test harnesses) does the authority fall back to the data root, whose
    owner is the same interactive principal in that mode.
    """
    if config_file is not None:
        return config_file.parent / LEGACY_CLASSIFICATION_FILENAME
    return Path(data_root) / LEGACY_CLASSIFICATION_FILENAME


def directory_permissions(
    *,
    owner: str,
    group: str,
    mode: int,
    user: str,
    user_group: str,
) -> dict[str, bool]:
    """Pure POSIX permission resolution for one DIRECTORY of the authority
    installation contract.

    Returns ``{"readable": bool, "writable": bool, "traversable": bool}``
    for an account identified by its user name and primary group name.
    Directory ``writable`` is the key trust-boundary bit: with it the
    principal may create, unlink, and rename entries inside the
    directory (i.e., replace a pathname), which is exactly the property
    the service principal must NOT have over the authority parent.
    """
    if user == owner:
        read_bits = 0o400
        write_bits = 0o200
        exec_bits = 0o100
    elif user_group == group:
        read_bits = 0o040
        write_bits = 0o020
        exec_bits = 0o010
    else:
        read_bits = 0o004
        write_bits = 0o002
        exec_bits = 0o001
    return {
        "readable": bool(mode & read_bits),
        "writable": bool(mode & write_bits),
        "traversable": bool(mode & exec_bits),
    }


def classification_authority_permissions(
    *,
    owner: str,
    group: str,
    mode: int,
    user: str,
    user_group: str,
) -> dict[str, bool]:
    """Pure POSIX permission resolution for the authority FILE contract.

    Returns ``{"readable": bool, "writable": bool}`` for an account
    identified by its user name and primary group name, given the
    documented final file owner/group/mode.  The deterministic contract
    test combines this file model with ``directory_permissions`` for the
    parent directory: content writes are governed by the file mode, but
    pathname replacement (unlink/rename) is governed by the PARENT
    directory's write bit (M21.4.11-R3.4).
    """
    if user == owner:
        read_bits = 0o400
        write_bits = 0o200
    elif user_group == group:
        read_bits = 0o040
        write_bits = 0o020
    else:
        read_bits = 0o004
        write_bits = 0o002
    return {
        "readable": bool(mode & read_bits),
        "writable": bool(mode & write_bits),
    }


class LegacyReconnectConflictError(CatalogStateError):
    """Raised when the legacy reconnect partition cannot proceed safely."""


def _canonical_json(document: object) -> str:
    return json.dumps(
        document, sort_keys=True, separators=(",", ":"), ensure_ascii=True
    )


def classification_evidence_sha256(
    *,
    chunk_id: str,
    intent: Mapping[str, object],
    verified_frames: object,
) -> str:
    """Deterministic binding digest of the COMPLETE immutable candidate
    classification evidence (M21.4.11-R3.3 REV-002).

    The digest is ``sha256(canonical_json({"chunk_id": chunk_id,
    "seal_intent": intent, "verified_frames": verified_frames}))`` where
    ``canonical_json`` uses sorted keys, compact separators, and ASCII
    escaping.  It covers the exact persisted SEALING transition evidence
    values that the operator reviewed and that the decision engine
    consumes:

    - ``chunk_id``: the immutable chunk identity;
    - ``seal_intent``: the exact immutable seal-intent document (including
      its ``intent_schema`` provenance when present);
    - ``verified_frames``: the exact immutable SEALING evidence value that
      drives the frame-bearing legitimacy proof (JSON ``null`` when the
      SEALING evidence carries no ``verified_frames`` field).

    Changing ANY immutable candidate-side fact that can change
    classification (chunk identity, intent identity fields, intent schema,
    or verified_frames) invalidates a stored authority digest.  No
    mutable/live field, filesystem path, current time, or derived operator
    note is part of the binding.  Historical lifecycle CONTEXT is not part
    of the candidate digest: startup always recomputes the automatic
    decision against the live Catalog first, and an authority entry whose
    candidate is later proven or conflicted fails closed as a
    contradiction (context staleness rule).
    """
    payload = _canonical_json(
        {
            "chunk_id": chunk_id,
            "seal_intent": dict(intent),
            "verified_frames": verified_frames,
        }
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class LegacyClassificationEntry:
    gap_id: str
    market: str
    symbol: str
    stream: str
    chunk_id: str
    classification_evidence_sha256: str
    classification: str
    note: str | None

    @property
    def binding(self) -> tuple[str, str, str, str, str, str]:
        return (
            self.market,
            self.symbol,
            self.stream,
            self.gap_id,
            self.chunk_id,
            self.classification_evidence_sha256,
        )


class LegacyClassificationAuthority:
    """Operator-reviewed additive authority (schema v3, strongly bound).

    Each entry binds the exact immutable persisted classification evidence
    via ``(market, symbol, stream, gap_id, chunk_id,
    classification_evidence_sha256)`` where the digest covers chunk_id +
    the exact seal intent + the exact ``verified_frames`` SEALING value.
    The authority resolves ONLY candidates the decision engine classified
    AMBIGUOUS.  Loading fails closed on malformed JSON, wrong schema
    (including the never-deployed v1/v2), unknown classification kinds,
    malformed digests, missing identity fields, unknown keys, and
    duplicate bindings.
    """

    def __init__(
        self, entries: dict[tuple[str, str, str, str], LegacyClassificationEntry]
    ) -> None:
        self._entries = dict(entries)

    @classmethod
    def load(cls, authority_path: Path) -> LegacyClassificationAuthority:
        path = Path(authority_path)
        if not path.exists():
            return cls({})
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise LegacyReconnectConflictError(
                "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                f"path={path}: cannot parse authority document: {exc}"
            ) from exc
        if not isinstance(document, dict):
            raise LegacyReconnectConflictError(
                "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                f"path={path}: authority must be a JSON object"
            )
        if set(document.keys()) != {"schema", "classifications"}:
            raise LegacyReconnectConflictError(
                "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                f"path={path}: authority must contain exactly schema and "
                "classifications"
            )
        schema = document["schema"]
        if schema != LEGACY_CLASSIFICATION_SCHEMA_V3:
            raise LegacyReconnectConflictError(
                "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                f"path={path}: unsupported authority schema {schema!r}; "
                f"expected {LEGACY_CLASSIFICATION_SCHEMA_V3!r}"
            )
        entries = document["classifications"]
        if not isinstance(entries, list):
            raise LegacyReconnectConflictError(
                "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                f"path={path}: classifications must be a list"
            )
        loaded: dict[tuple[str, str, str, str], LegacyClassificationEntry] = {}
        seen_bindings: set[tuple[str, str, str, str, str, str]] = set()
        for index, entry in enumerate(entries):
            if not isinstance(entry, dict):
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} must be an object"
                )
            if set(entry.keys()) - {
                "gap_id",
                "market",
                "symbol",
                "stream",
                "chunk_id",
                "classification_evidence_sha256",
                "classification",
                "note",
            }:
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} carries unknown keys"
                )
            gap_id = entry.get("gap_id")
            market = entry.get("market")
            symbol = entry.get("symbol", LEGACY_SINGLE_SYMBOL)
            stream = entry.get("stream")
            chunk_id = entry.get("chunk_id")
            digest = entry.get("classification_evidence_sha256")
            classification = entry.get("classification")
            note = entry.get("note")
            if (
                not isinstance(gap_id, str)
                or not gap_id
                or not isinstance(market, str)
                or not market
                or not isinstance(symbol, str)
                or not symbol
                or not isinstance(stream, str)
                or not stream
                or not isinstance(chunk_id, str)
                or not chunk_id
            ):
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} has invalid identity"
                )
            if not isinstance(digest, str) or not _DIGEST_PATTERN.fullmatch(
                digest
            ):
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} has an invalid "
                    "classification_evidence_sha256 (expected 64 lowercase "
                    "hex chars)"
                )
            if classification not in LEGACY_CLASSIFICATION_KINDS:
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} has unknown classification "
                    f"{classification!r}"
                )
            if note is not None and not isinstance(note, str):
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: entry {index} note must be text"
                )
            identity = (market, symbol, stream, gap_id)
            if identity in loaded:
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: duplicate classification for {gap_id}"
                )
            binding = (market, symbol, stream, gap_id, chunk_id, digest)
            if binding in seen_bindings:
                raise LegacyReconnectConflictError(
                    "RECOVERY_LEGACY_CLASSIFICATION_MALFORMED "
                    f"path={path}: duplicate binding for {gap_id}"
                )
            seen_bindings.add(binding)
            loaded[identity] = LegacyClassificationEntry(
                gap_id=gap_id,
                market=market,
                symbol=symbol,
                stream=stream,
                chunk_id=chunk_id,
                classification_evidence_sha256=digest,
                classification=classification,
                note=note,
            )
        return cls(loaded)

    def entries(self) -> tuple[LegacyClassificationEntry, ...]:
        return tuple(self._entries.values())

    def lookup(
        self, *, market: str, symbol: str, stream: str, gap_id: str
    ) -> LegacyClassificationEntry | None:
        return self._entries.get((market, symbol, stream, gap_id))


def validate_seal_intent(
    intent: Mapping[str, object], chunk_id: str
) -> None:
    """Reject a malformed seal-intent document before classification.

    An optional ``intent_schema`` provenance field is validated strictly
    (M21.4.11-R3.3/R3.4): when the key is PRESENT its value must be
    exactly the current ``reconnect-seal-intent.v2`` contract; an unknown
    future schema, an empty string, a non-text value, or an explicit
    ``null`` all fail closed (R3.3-SCHEMA-001).  Only a MISSING key marks
    a pre-R3 unversioned legacy intent, which follows the conservative
    legacy policy.
    """

    if "intent_schema" in intent:
        schema = intent["intent_schema"]
        if not isinstance(schema, str) or schema != RECONNECT_INTENT_SCHEMA_V2:
            raise LegacyReconnectConflictError(
                "RECOVERY_SEAL_INTENT_UNSUPPORTED_SCHEMA "
                f"chunk={chunk_id} schema={schema!r} expected "
                f"{RECONNECT_INTENT_SCHEMA_V2!r}"
            )
    required_names = (
        "required_forced_flags",
        "gap_id",
        "reason",
        "market",
        "symbol",
        "stream",
        "original_connection_id",
        "original_generation",
        "gap_started_at_utc_ns",
    )
    for name in required_names:
        if name not in intent:
            raise LegacyReconnectConflictError(
                f"RECOVERY_SEAL_INTENT_MISSING_FIELD {name} chunk={chunk_id}"
            )
    flags = intent["required_forced_flags"]
    if not isinstance(flags, list) or not all(
        isinstance(flag, str) and flag for flag in flags
    ):
        raise LegacyReconnectConflictError(
            f"RECOVERY_SEAL_INTENT_INVALID_FLAGS chunk={chunk_id}"
        )
    gap_id = intent["gap_id"]
    reason = intent["reason"]
    market = intent["market"]
    symbol = intent["symbol"]
    stream = intent["stream"]
    connection_id = intent["original_connection_id"]
    generation = intent["original_generation"]
    started_at = intent["gap_started_at_utc_ns"]
    if not all(
        isinstance(value, str) and value
        for value in (gap_id, reason, market, symbol, stream, connection_id)
    ):
        raise LegacyReconnectConflictError(
            f"RECOVERY_SEAL_INTENT_INVALID_IDENTITY chunk={chunk_id}"
        )
    if (
        isinstance(generation, bool)
        or not isinstance(generation, int)
        or generation < 0
    ):
        raise LegacyReconnectConflictError(
            f"RECOVERY_SEAL_INTENT_INVALID_GENERATION chunk={chunk_id}"
        )
    if (
        isinstance(started_at, bool)
        or not isinstance(started_at, int)
        or started_at < 0
    ):
        raise LegacyReconnectConflictError(
            f"RECOVERY_SEAL_INTENT_INVALID_STARTED_AT chunk={chunk_id}"
        )


